#!/bin/sh
# Turns lib/*.py into C string tables: pylib_names[] and pylib_sources[].
echo '/* Generated by tools/embed.sh. Do not edit. */'
echo '#include <stddef.h>'
i=0
for f in "$@"; do
    printf 'static const char src_%d[] = {' "$i"
    od -An -v -tu1 "$f" | tr -s ' \n' ',' | sed 's/^,//'
    echo '0};'
    i=$((i + 1))
done
echo 'const char *const pylib_names[] = {'
for f in "$@"; do printf '    "%s",\n' "$(basename "$f" .py)"; done
echo '    NULL};'
echo 'const char *const pylib_sources[] = {'
i=0
for f in "$@"; do printf '    src_%d,\n' "$i"; i=$((i + 1)); done
echo '    NULL};'
